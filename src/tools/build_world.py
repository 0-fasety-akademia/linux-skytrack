#!/usr/bin/env python3
"""Build web/world.js — country outlines for the offline map.

Source: world-atlas 2.0.2 countries-50m.json (TopoJSON of Natural Earth 1:50m, public domain;
world-atlas ISC). Numeric ISO 3166 ids are mapped to alpha-2 (property "cc") using the system's
iso-codes package (/usr/share/iso-codes/json/iso_3166-1.json).

Usage: python3 tools/build_world.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "data", "src", "countries-50m.json")
OUT = os.path.join(ROOT, "web", "world.js")
EXTRA = {"Kosovo": "XK", "N. Cyprus": "CY", "Somaliland": "SO"}


def main():
    with open("/usr/share/iso-codes/json/iso_3166-1.json", encoding="utf-8") as f:
        iso = {c["numeric"]: c["alpha_2"] for c in json.load(f)["3166-1"]}
    with open(SRC, encoding="utf-8") as f:
        topo = json.load(f)
    missing = []
    for g in topo["objects"]["countries"]["geometries"]:
        name = (g.get("properties") or {}).get("name", "")
        cc = iso.get(str(g.get("id", "")).zfill(3)) or EXTRA.get(name, "")
        g["properties"] = {"cc": cc, "name": name}
        g.pop("id", None)
        if not cc:
            missing.append(name)
    topo["objects"] = {"countries": topo["objects"]["countries"]}   # drop the land object
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Natural Earth 1:50m via world-atlas 2.0.2 (ISC) — generated by tools/build_world.py */\n")
        f.write("window.WORLD_TOPO = ")
        json.dump(topo, f, separators=(",", ":"))
        f.write(";\n")
    print("written", OUT, os.path.getsize(OUT) // 1024, "KiB; without code:", missing)


if __name__ == "__main__":
    main()
